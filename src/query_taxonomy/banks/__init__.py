# Resolution sorts stably by AmbiguityTier, so tuple order = claim priority
# within a tier. Order constraints are load-bearing:
#   - CIDRBank before IPAddressBank: claims 192.168.0.0/16 whole
#   - URIBank before EmailBank: userinfo URLs (https://user:pass@host) stay one URI
#   - URIBank (RIGID) beats HostPortBank (MODERATE): full URLs > bare-domain claims
#   - EmailBank before (future) SocialHandleBank: @domain stays part of the email
#   - (future) PackageCoordinateBank before SocialHandleBank: @scope/name > @scope
#   - CodeIdentifierBank before NumberBank: both AMBIGUOUS, dotted paths first
#   - CVEBank (RIGID) beats TicketLikeBank (MODERATE): CVE-2024-3094 is not a ticket
#   - SecuritiesIdBank before MarketCodeBank: all-numeric CUSIP vs 9-digit ABA
#   - LEIBank/IBANBank before BICBank/StockTickerLikeBank: long codes claim first
#   - BICBank before StockTickerLikeBank: 8/11-cap BIC beats 2-5-cap bare ticker
#   - MarketCodeBank before NumberBank: 9-digit ABA beats plain number
